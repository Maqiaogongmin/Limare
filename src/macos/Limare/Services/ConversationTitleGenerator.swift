import Foundation

struct ConversationTitleRequestPlan: Sendable {
    let messages: [ChatRequestMessage]
    let tools: [ChatToolDefinition]
    let options: ChatInferenceOptions
}

@MainActor
final class ConversationTitleGenerator {
    static let maximumExcerptCharacters = 200
    static let maximumTitleCharacters = 80
    static let maximumOutputTokens = 256

    private let resolver: SubModelResolver
    private let providers: ProviderStore
    private let client: any ProviderClient
    private let logs: DebugLogStore

    init(
        resolver: SubModelResolver,
        providers: ProviderStore,
        client: any ProviderClient = OpenAICompatibleClient(),
        logs: DebugLogStore
    ) {
        self.resolver = resolver
        self.providers = providers
        self.client = client
        self.logs = logs
    }

    func generateTitle(for conversation: ConversationRecord) async -> String {
        let fallback = Self.localFallbackTitle(for: conversation)
        guard Self.shouldGenerateTitle(for: conversation),
              let summary = Self.summary(for: conversation) else { return fallback }

        let candidates = resolver.orderedCandidates(
            subSource: conversation.subModelSource,
            primarySource: conversation.effectiveModelSource,
            conversationID: conversation.id
        )
        for (index, candidate) in candidates.enumerated() {
            do {
                let apiKey = try providers.apiKey(providerID: candidate.provider.id)
                let title = try await requestTitle(candidate: candidate, apiKey: apiKey, summary: summary)
                logs.info("TitleGeneration", "Conversation \(conversation.id) title generated by \(candidate.attribution), attempt \(index + 1): \(title)")
                return title
            } catch {
                logs.error("TitleGeneration", "Conversation \(conversation.id) title candidate \(candidate.attribution), attempt \(index + 1) failed: \(error.localizedDescription)")
            }
        }
        logs.info("TitleGeneration", "Conversation \(conversation.id) used local title fallback after model candidates were exhausted.")
        return fallback
    }

    static func shouldGenerateTitle(for conversation: ConversationRecord) -> Bool {
        let title = conversation.title.trimmingCharacters(in: .whitespacesAndNewlines)
        guard title.isEmpty || title == ConversationRecord.defaultTitle else { return false }
        return conversation.messages.contains {
            $0.role == .assistant
                && $0.state == .complete
                && !$0.content.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        }
    }

    static func summary(for conversation: ConversationRecord) -> String? {
        let users = conversation.messages.filter { $0.role == .user }
        let assistants = conversation.messages.filter {
            $0.role == .assistant && $0.state == .complete
                && !$0.content.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        }
        guard let firstUser = users.first, let firstAssistant = assistants.first else { return nil }

        func userText(_ message: ChatMessage) -> String {
            let text = message.content.trimmingCharacters(in: .whitespacesAndNewlines)
            return text.isEmpty && !message.attachments.isEmpty ? "[Image attachment]" : text
        }
        func excerpt(_ text: String) -> String {
            String(Self.collapseWhitespace(text).prefix(Self.maximumExcerptCharacters))
        }

        var result = "First User: \(excerpt(userText(firstUser)))\n\nFirst Assistant: \(excerpt(firstAssistant.content))"
        if users.count > 1, let lastUser = users.last {
            result += "\n\n[Middle omitted]\n\nLast User: \(excerpt(userText(lastUser)))"
            if let lastAssistant = assistants.last, lastAssistant.id != firstAssistant.id {
                result += "\n\nLast Assistant: \(excerpt(lastAssistant.content))"
            }
        }
        return result
    }

    static func localFallbackTitle(for conversation: ConversationRecord) -> String {
        guard let firstUser = conversation.messages.first(where: { $0.role == .user }) else {
            return String(localized: "Image Conversation")
        }
        let text = collapseWhitespace(firstUser.content)
        guard !text.isEmpty else { return String(localized: "Image Conversation") }
        return boundedTitle(text, maximum: 35)
    }

    static func parseTitle(_ raw: String) -> String? {
        var text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if text.hasPrefix("```") {
            text = text.replacingOccurrences(of: "^```(?:json)?\\s*", with: "", options: .regularExpression)
                .replacingOccurrences(of: "\\s*```$", with: "", options: .regularExpression)
        }

        func decodedTitle(_ candidate: String) -> String? {
            guard let data = candidate.data(using: .utf8),
                  let object = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let title = object["title"] as? String else { return nil }
            return sanitizeTitle(title)
        }
        if let title = decodedTitle(text) { return title }
        if let start = text.firstIndex(of: "{"), let end = text.lastIndex(of: "}"), start <= end,
           let title = decodedTitle(String(text[start...end])) { return title }
        guard !text.isEmpty, !text.contains("{"), !text.contains("}"), text.count <= 200 else { return nil }
        return sanitizeTitle(text)
    }

    static func requestPlan(summary: String, model: ProviderModel) -> ConversationTitleRequestPlan {
        ConversationTitleRequestPlan(
            messages: [
                ChatRequestMessage(
                    role: "system",
                    content: "You generate concise conversation titles. Return one JSON object only: {\"title\":\"...\"}"
                ),
                ChatRequestMessage(
                    role: "user",
                    content: "Generate a short title that captures the topic. Use the same language as the conversation. Do not mention that you are generating a title.\n\nConversation:\n\(summary)"
                )
            ],
            tools: [],
            options: ChatInferenceOptions(
                thinkingLevel: .off,
                maxOutputTokens: maximumOutputTokens,
                model: model
            )
        )
    }

    private func requestTitle(candidate: SubModelCandidate, apiKey: String, summary: String) async throws -> String {
        let plan = Self.requestPlan(summary: summary, model: candidate.model)
        var raw = ""
        let stream = client.streamChat(
            provider: candidate.provider,
            apiKey: apiKey,
            modelID: candidate.model.id,
            messages: plan.messages,
            tools: plan.tools,
            options: plan.options,
            attachmentResolver: nil
        )
        for try await event in stream {
            if case .textDelta(let delta) = event { raw += delta }
        }
        guard let title = Self.parseTitle(raw) else {
            throw ProviderClientError.invalidResponse
        }
        return title
    }

    private static func sanitizeTitle(_ raw: String) -> String? {
        let collapsed = collapseWhitespace(raw)
            .trimmingCharacters(in: CharacterSet(charactersIn: "\"'“”‘’"))
        guard !collapsed.isEmpty else { return nil }
        return boundedTitle(collapsed, maximum: maximumTitleCharacters)
    }

    private static func collapseWhitespace(_ text: String) -> String {
        text.replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private static func boundedTitle(_ title: String, maximum: Int) -> String {
        guard title.count > maximum else { return title }
        return String(title.prefix(maximum)).trimmingCharacters(in: .whitespacesAndNewlines) + "…"
    }
}
